import { type ChatMessage, type LMClient } from './lmClient';

/**
 * A TypeScript implementation of the core DSPy ideas, faithful to the real
 * framework so that what you learn here transfers directly.
 *
 * What is reproduced exactly:
 *  - Signatures: typed input and output fields plus a natural-language objective.
 *  - The ChatAdapter prompt format, including the [[ ## field ## ]] markers.
 *  - BootstrapFewShot: run the program, keep the traces that pass the metric,
 *    and reuse those as demonstrations.
 *  - COPRO-style instruction search: have the model propose new instructions,
 *    score each on real data, keep the winner.
 *  - MIPRO-style joint search over instruction and demonstration combinations.
 *
 * This is a reimplementation, not a binding to the Python package. The Export
 * tab emits the equivalent real DSPy program so a run can be reproduced there.
 */

export interface Field {
  name: string;
  desc: string;
}

export interface Signature {
  name: string;
  instructions: string;
  inputs: Field[];
  outputs: Field[];
}

export interface Example {
  id: string;
  inputs: Record<string, string>;
  outputs: Record<string, string>;
}

export interface Demo {
  inputs: Record<string, string>;
  outputs: Record<string, string>;
  /** True when this demo was generated by the model rather than hand-labelled. */
  bootstrapped: boolean;
}

export interface Program {
  signature: Signature;
  demos: Demo[];
  /** Chain of thought prepends a reasoning field the model must fill first. */
  cot: boolean;
}

export interface Prediction {
  outputs: Record<string, string>;
  raw: string;
  messages: ChatMessage[];
  error?: string;
}

const REASONING: Field = {
  name: 'reasoning',
  desc: 'Think step by step before answering.',
};

export function effectiveOutputs(p: Program): Field[] {
  return p.cot ? [REASONING, ...p.signature.outputs] : p.signature.outputs;
}

/* ------------------------------------------------------------- adapter -- */

function fieldList(fields: Field[]): string {
  return fields.map((f, i) => `${i + 1}. \`${f.name}\` (str): ${f.desc}`).join('\n');
}

function fieldBlock(name: string, value: string): string {
  return `[[ ## ${name} ## ]]\n${value}`;
}

/** The system prompt, in the same shape DSPy ChatAdapter produces. */
export function buildSystemMessage(p: Program): string {
  const outs = effectiveOutputs(p);
  const structure = [
    ...p.signature.inputs.map((f) => fieldBlock(f.name, `{${f.name}}`)),
    ...outs.map((f) => fieldBlock(f.name, `{${f.name}}`)),
    '[[ ## completed ## ]]',
  ].join('\n\n');

  return [
    'Your input fields are:',
    fieldList(p.signature.inputs),
    '',
    'Your output fields are:',
    fieldList(outs),
    '',
    'All interactions will be structured in the following way, with the appropriate values filled in.',
    '',
    structure,
    '',
    `In adhering to this structure, your objective is:`,
    `        ${p.signature.instructions}`,
  ].join('\n');
}

function userTurn(p: Program, inputs: Record<string, string>): string {
  const blocks = p.signature.inputs.map((f) => fieldBlock(f.name, inputs[f.name] ?? ''));
  const outs = effectiveOutputs(p);
  blocks.push(
    `Respond with the corresponding output fields, starting with the field ` +
      outs.map((f) => `\`[[ ## ${f.name} ## ]]\``).join(', then ') +
      `, and then ending with the marker for \`[[ ## completed ## ]]\`.`,
  );
  return blocks.join('\n\n');
}

function assistantTurn(p: Program, outputs: Record<string, string>): string {
  const outs = effectiveOutputs(p);
  return (
    outs.map((f) => fieldBlock(f.name, outputs[f.name] ?? '')).join('\n\n') + '\n\n[[ ## completed ## ]]'
  );
}

/** Full message list for one call, demos included. */
export function buildMessages(p: Program, inputs: Record<string, string>): ChatMessage[] {
  const msgs: ChatMessage[] = [{ role: 'system', content: buildSystemMessage(p) }];
  for (const d of p.demos) {
    msgs.push({ role: 'user', content: userTurn(p, d.inputs) });
    msgs.push({ role: 'assistant', content: assistantTurn(p, d.outputs) });
  }
  msgs.push({ role: 'user', content: userTurn(p, inputs) });
  return msgs;
}

/** Pull `[[ ## field ## ]]` sections back out of the model response. */
export function parseResponse(p: Program, raw: string): Record<string, string> {
  const outs = effectiveOutputs(p);
  const result: Record<string, string> = {};
  const re = /\[\[ ## ([a-zA-Z0-9_]+) ## \]\]/g;
  const marks: { name: string; start: number; end: number }[] = [];
  let m: RegExpExecArray | null;
  while ((m = re.exec(raw)) !== null) {
    marks.push({ name: m[1], start: m.index, end: m.index + m[0].length });
  }
  if (marks.length === 0) {
    // Model ignored the format. Fall back to giving the whole reply to the
    // first non-reasoning output field, which is what DSPy does too.
    const target = outs.find((f) => f.name !== 'reasoning') ?? outs[0];
    if (target) result[target.name] = raw.trim();
    return result;
  }
  for (let i = 0; i < marks.length; i++) {
    const cur = marks[i];
    if (cur.name === 'completed') continue;
    const stop = i + 1 < marks.length ? marks[i + 1].start : raw.length;
    result[cur.name] = raw.slice(cur.end, stop).trim();
  }
  return result;
}

export async function runProgram(
  client: LMClient,
  p: Program,
  inputs: Record<string, string>,
  tag = 'predict',
  signal?: AbortSignal,
): Promise<Prediction> {
  const messages = buildMessages(p, inputs);
  try {
    const raw = await client.complete(messages, tag, signal);
    return { outputs: parseResponse(p, raw), raw, messages };
  } catch (err) {
    return {
      outputs: {},
      raw: '',
      messages,
      error: err instanceof Error ? err.message : String(err),
    };
  }
}

/* -------------------------------------------------------------- metrics -- */

export type Metric = (ex: Example, pred: Prediction) => number;

export interface MetricDef {
  id: string;
  label: string;
  blurb: string;
  fn: (field: string) => Metric;
}

const norm = (s: string) =>
  (s ?? '')
    .toLowerCase()
    .replace(/[.,!?;:"']/g, '')
    .replace(/\b(a|an|the)\b/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

export const METRICS: MetricDef[] = [
  {
    id: 'exact',
    label: 'Exact match',
    blurb: 'Scores 1 only when the answer matches the label after lowercasing and stripping punctuation. Strict and unforgiving.',
    fn: (field) => (ex, pred) => (norm(pred.outputs[field]) === norm(ex.outputs[field]) ? 1 : 0),
  },
  {
    id: 'contains',
    label: 'Contains answer',
    blurb: 'Scores 1 when the gold answer appears anywhere in the prediction. Tolerant of a chatty model.',
    fn: (field) => (ex, pred) => {
      const g = norm(ex.outputs[field]);
      const p = norm(pred.outputs[field]);
      return g.length > 0 && p.includes(g) ? 1 : 0;
    },
  },
  {
    id: 'f1',
    label: 'Token F1',
    blurb: 'Word-overlap score between prediction and label. Gives partial credit, which makes optimizer progress easier to see.',
    fn: (field) => (ex, pred) => {
      const g = norm(ex.outputs[field]).split(' ').filter(Boolean);
      const p = norm(pred.outputs[field]).split(' ').filter(Boolean);
      if (g.length === 0 || p.length === 0) return 0;
      const counts = new Map<string, number>();
      for (const w of g) counts.set(w, (counts.get(w) ?? 0) + 1);
      let overlap = 0;
      for (const w of p) {
        const c = counts.get(w) ?? 0;
        if (c > 0) {
          overlap++;
          counts.set(w, c - 1);
        }
      }
      if (overlap === 0) return 0;
      const precision = overlap / p.length;
      const recall = overlap / g.length;
      return (2 * precision * recall) / (precision + recall);
    },
  },
  {
    id: 'numeric',
    label: 'Numeric match',
    blurb: 'Extracts the last number from each side and compares them. The right choice for arithmetic tasks.',
    fn: (field) => (ex, pred) => {
      const last = (s: string) => {
        const all = (s ?? '').match(/-?\d+(?:\.\d+)?/g);
        return all ? parseFloat(all[all.length - 1]) : NaN;
      };
      const a = last(pred.outputs[field]);
      const b = last(ex.outputs[field]);
      return Number.isFinite(a) && Number.isFinite(b) && Math.abs(a - b) < 1e-6 ? 1 : 0;
    },
  },
];

/* ----------------------------------------------------------- evaluation -- */

export interface EvalResult {
  example: Example;
  prediction: Prediction;
  score: number;
}

export interface EvalSummary {
  score: number;
  results: EvalResult[];
  promptTokens: number;
  completionTokens: number;
  calls: number;
  wallMs: number;
}

export async function evaluate(
  client: LMClient,
  program: Program,
  examples: Example[],
  metric: Metric,
  opts: {
    tag?: string;
    concurrency?: number;
    onProgress?: (done: number, total: number, r: EvalResult) => void;
    signal?: AbortSignal;
  } = {},
): Promise<EvalSummary> {
  const { tag = 'eval', concurrency = 4, onProgress, signal } = opts;
  const t0 = performance.now();
  const before = { p: client.totalPromptTokens, c: client.totalCompletionTokens, n: client.calls.length };
  const results: EvalResult[] = new Array(examples.length);
  let done = 0;
  let cursor = 0;

  const worker = async () => {
    for (;;) {
      const i = cursor++;
      if (i >= examples.length) return;
      if (signal?.aborted) return;
      const ex = examples[i];
      const pred = await runProgram(client, program, ex.inputs, tag, signal);
      const score = pred.error ? 0 : metric(ex, pred);
      const r = { example: ex, prediction: pred, score };
      results[i] = r;
      done++;
      onProgress?.(done, examples.length, r);
    }
  };

  await Promise.all(Array.from({ length: Math.min(concurrency, examples.length) }, worker));
  const filled = results.filter(Boolean);
  return {
    score: filled.length ? filled.reduce((a, r) => a + r.score, 0) / filled.length : 0,
    results: filled,
    promptTokens: client.totalPromptTokens - before.p,
    completionTokens: client.totalCompletionTokens - before.c,
    calls: client.calls.length - before.n,
    wallMs: performance.now() - t0,
  };
}

