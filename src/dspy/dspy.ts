export interface OptimizerEvent {
  kind: 'info' | 'candidate' | 'best' | 'trace' | 'error';
  msg: string;
  score?: number;
  detail?: string;
}

export interface OptimizeOpts {
  trainset: Example[];
  valset: Example[];
  metric: Metric;
  maxDemos: number;
  candidates: number;
  rounds: number;
  minibatch: number;
  onEvent?: (e: OptimizerEvent) => void;
  signal?: AbortSignal;
}

export interface Candidate {
  label: string;
  program: Program;
  score: number;
}

export interface OptimizeResult {
  program: Program;
  baselineScore: number;
  optimizedScore: number;
  events: OptimizerEvent[];
  tried: { instructions: string; demoCount: number; score: number }[];
  /**
   * Every candidate that was built and scored, winner or not. Kept so the UI
   * can show what an optimizer tried, including work that did not pay off.
   */
  candidatePrograms: Candidate[];
}

function shuffled<T>(arr: T[], rand: () => number): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** Deterministic, so a demo run reproduces exactly. */
function rng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Run the program over the training set and keep the traces it got right.
 * This is the heart of BootstrapFewShot.
 */
async function bootstrapDemos(
  client: LMClient,
  program: Program,
  opts: OptimizeOpts,
  limit: number,
  emit: (e: OptimizerEvent) => void,
  seed = 1,
): Promise<Demo[]> {
  const demos: Demo[] = [];
  const pool = shuffled(opts.trainset, rng(seed));
  for (const ex of pool) {
    if (demos.length >= limit) break;
    if (opts.signal?.aborted) break;
    const pred = await runProgram(client, program, ex.inputs, 'bootstrap', opts.signal);
    if (pred.error) {
      emit({ kind: 'error', msg: `call failed on ${ex.id}: ${pred.error}` });
      continue;
    }
    const score = opts.metric(ex, pred);
    if (score >= 1) {
      // Keep the model-generated fields, but pin the gold label so the demo
      // teaches the correct answer rather than a lucky one.
      const outputs: Record<string, string> = { ...pred.outputs, ...ex.outputs };
      demos.push({ inputs: ex.inputs, outputs, bootstrapped: true });
      emit({
        kind: 'trace',
        msg: `kept trace for ${ex.id} (metric ${score.toFixed(2)})`,
        score,
        detail: effectiveOutputs(program)
          .map((f) => `${f.name}: ${outputs[f.name] ?? ''}`)
          .join('\n'),
      });
    } else {
      emit({ kind: 'info', msg: `discarded ${ex.id} (metric ${score.toFixed(2)})`, score });
    }
  }
  return demos;
}

/** Ask the model to propose better instruction strings for its own task. */
async function proposeInstructions(
  client: LMClient,
  program: Program,
  history: { instructions: string; score: number }[],
  n: number,
  opts: OptimizeOpts,
): Promise<string[]> {
  const task = [
    `You are optimizing the instruction string for a language model program.`,
    ``,
    `The program takes these inputs: ${program.signature.inputs.map((f) => f.name).join(', ')}`,
    `and must produce these outputs: ${program.signature.outputs.map((f) => f.name).join(', ')}.`,
    ``,
    `Instructions tried so far, with their measured scores:`,
    ...history
      .slice()
      .sort((a, b) => a.score - b.score)
      .map((h) => `  score ${h.score.toFixed(3)}: ${h.instructions}`),
    ``,
    `Propose ${n} new instruction strings that should score higher.`,
    `Be specific about the format and reasoning the task requires.`,
    `Return one per line, numbered, with no other commentary.`,
  ].join('\n');

  try {
    const raw = await client.complete(
      [{ role: 'user', content: task }],
      'propose-instructions',
      opts.signal,
    );
    return raw
      .split('\n')
      .map((l) => l.replace(/^\s*\d+[.)]\s*/, '').trim())
      .filter((l) => l.length > 12)
      .slice(0, n);
  } catch {
    return [];
  }
}

export async function optimize(
  client: LMClient,
  base: Program,
  id: OptimizerId,
  opts: OptimizeOpts,
): Promise<OptimizeResult> {
  const events: OptimizerEvent[] = [];
  const tried: { instructions: string; demoCount: number; score: number }[] = [];
  const candidatePrograms: Candidate[] = [];
  const emit = (e: OptimizerEvent) => {
    events.push(e);
    opts.onEvent?.(e);
  };
  const record = (label: string, program: Program, score: number) => {
    candidatePrograms.push({ label, program, score });
    tried.push({ instructions: program.signature.instructions, demoCount: program.demos.length, score });
  };

  emit({ kind: 'info', msg: `scoring the unoptimized program on ${opts.valset.length} held-out examples` });
  const baseEval = await evaluate(client, base, opts.valset, opts.metric, {
    tag: 'baseline',
    signal: opts.signal,
  });
  emit({ kind: 'best', msg: `baseline score`, score: baseEval.score });
  record('Unoptimized baseline', base, baseEval.score);

  let best: Program = { ...base, demos: [...base.demos] };
  let bestScore = baseEval.score;

  const scoreOn = async (p: Program, set: Example[], tag: string) => {
    const r = await evaluate(client, p, set, opts.metric, { tag, signal: opts.signal });
    return r.score;
  };

  if (id === 'labeled') {
    const rand = rng(11);
    const picked = shuffled(opts.trainset, rand).slice(0, opts.maxDemos);
    const cand: Program = {
      ...base,
      demos: picked.map((e) => ({ inputs: e.inputs, outputs: e.outputs, bootstrapped: false })),
    };
    emit({ kind: 'info', msg: `selected ${picked.length} labelled examples as demonstrations` });
    const s = await scoreOn(cand, opts.valset, 'labeled');
    record(`LabeledFewShot (${cand.demos.length} demos)`, cand, s);
    emit({ kind: 'candidate', msg: `LabeledFewShot with ${picked.length} demos`, score: s });
    if (s > bestScore) {
      best = cand;
      bestScore = s;
    }
  }

  if (id === 'bootstrap') {
    emit({ kind: 'info', msg: `running the program over the training set to harvest correct traces` });
    const demos = await bootstrapDemos(client, base, opts, opts.maxDemos, emit);
    emit({ kind: 'info', msg: `collected ${demos.length} passing traces` });
    if (demos.length === 0) {
      emit({ kind: 'error', msg: 'no training example passed the metric, so there is nothing to bootstrap from. Try a looser metric or an easier task.' });
    } else {
      const cand: Program = { ...base, demos };
      const s = await scoreOn(cand, opts.valset, 'bootstrap');
      record(`BootstrapFewShot (${demos.length} demos)`, cand, s);
      emit({ kind: 'candidate', msg: `BootstrapFewShot with ${demos.length} self-generated demos`, score: s });
      if (s > bestScore) {
        best = cand;
        bestScore = s;
      }
    }
  }

  if (id === 'copro') {
    const history = [{ instructions: base.signature.instructions, score: bestScore }];
    for (let round = 0; round < opts.rounds; round++) {
      if (opts.signal?.aborted) break;
      emit({ kind: 'info', msg: `round ${round + 1}: asking the model for ${opts.candidates} new instruction candidates` });
      const proposals = await proposeInstructions(client, best, history, opts.candidates, opts);
      if (proposals.length === 0) {
        emit({ kind: 'error', msg: 'the model returned no usable proposals' });
        break;
      }
      for (const text of proposals) {
        if (opts.signal?.aborted) break;
        const cand: Program = { ...best, signature: { ...best.signature, instructions: text } };
        const s = await scoreOn(cand, opts.valset, 'copro');
        history.push({ instructions: text, score: s });
        record('COPRO instruction candidate', cand, s);
        emit({ kind: 'candidate', msg: text, score: s });
        if (s > bestScore) {
          bestScore = s;
          best = cand;
          emit({ kind: 'best', msg: `new best instruction`, score: s, detail: text });
        }
      }
    }
  }

  if (id === 'mipro') {
    emit({ kind: 'info', msg: 'building a pool of demonstration sets' });
    const demoSets: Demo[][] = [[]];
    for (let i = 0; i < Math.min(3, opts.candidates); i++) {
      if (opts.signal?.aborted) break;
      const d = await bootstrapDemos(client, base, opts, opts.maxDemos, emit, 7 + i * 13);
      if (d.length) demoSets.push(d);
    }
    emit({ kind: 'info', msg: `${demoSets.length} demonstration sets available` });

    emit({ kind: 'info', msg: 'proposing instruction candidates' });
    const instr = [
      base.signature.instructions,
      ...(await proposeInstructions(client, base, [{ instructions: base.signature.instructions, score: bestScore }], opts.candidates, opts)),
    ];
    emit({ kind: 'info', msg: `${instr.length} instruction candidates available` });

    const rand = rng(23);
    const mini = shuffled(opts.valset, rand).slice(0, Math.max(3, Math.min(opts.minibatch, opts.valset.length)));
    const combos: { i: string; d: Demo[] }[] = [];
    for (const i of instr) for (const d of demoSets) combos.push({ i, d });
    const budget = Math.min(combos.length, Math.max(4, opts.candidates * 2));
    emit({ kind: 'info', msg: `searching ${budget} of ${combos.length} combinations on a ${mini.length}-example minibatch` });

    let bestCombo: { i: string; d: Demo[] } | null = null;
    let bestMini = -1;
    for (const c of shuffled(combos, rand).slice(0, budget)) {
      if (opts.signal?.aborted) break;
      const cand: Program = {
        ...base,
        signature: { ...base.signature, instructions: c.i },
        demos: c.d,
      };
      const s = await scoreOn(cand, mini, 'mipro-mini');
      record(`MIPRO combo (${c.d.length} demos)`, cand, s);
      emit({ kind: 'candidate', msg: `${c.d.length} demos | ${c.i.slice(0, 90)}`, score: s });
      if (s > bestMini) {
        bestMini = s;
        bestCombo = c;
      }
    }

    if (bestCombo) {
      const cand: Program = {
        ...base,
        signature: { ...base.signature, instructions: bestCombo.i },
        demos: bestCombo.d,
      };
      emit({ kind: 'info', msg: 'scoring the best combination on the full validation set' });
      const s = await scoreOn(cand, opts.valset, 'mipro-final');
      record('MIPRO best combination (full validation)', cand, s);
      emit({ kind: 'candidate', msg: 'best combination, full validation', score: s });
      if (s > bestScore) {
        bestScore = s;
        best = cand;
      }
    }
  }

  emit({ kind: 'best', msg: 'optimization finished', score: bestScore });
  return {
    program: best,
    baselineScore: baseEval.score,
    optimizedScore: bestScore,
    events,
    tried,
    candidatePrograms,
  };
}
